interface Parsed {
  pinned: string | null;
  title: string;
  one_line: string;
  nfr: string[];
  time?: number;
  langs?: string[];
  style?: string;
  level: Level;
  order: number;
}

function parseLine(line: string, level: Level, order: number): Parsed {
  const [head = "", one_line = "", nfr = "", opts = ""] = line.split("|");
  const pin = /^@([a-z]+-\d{4})\s+(.+)$/.exec(head.trim());
  const p: Parsed = {
    pinned: pin ? pin[1]! : null,
    title: (pin ? pin[2]! : head).trim(),
    one_line: one_line.trim(),
    nfr: nfr.split(",").map((s) => s.trim()).filter(Boolean),
    level,
    order,
  };
  for (const kv of opts.split(";").map((s) => s.trim()).filter(Boolean)) {
    const [k, v = ""] = kv.split("=");
    if (k === "t") p.time = Number(v);
    else if (k === "lang") p.langs = v.split(",").map((s) => s.trim());
    else if (k === "style") p.style = v;
    else throw new Error(`未知のオプション ${kv}（${line}）`);
  }
  if (!p.title || !p.one_line) throw new Error(`title / one_line が空: ${line}`);
  return p;
}

async function main(): Promise<void> {
  const root = problemsRoot();
  const targets = await readTargets(root);
  const entries = await loadEntries(root);
  const real = new Map(entries.flatMap((e) => (e.problem ? [[e.problem.meta.id, e.problem] as const] : [])));
  const errors: string[] = [];
  const seeds: SeedT[] = [];
  const usedPinned = new Set<string>();

  for (const cat of CATEGORIES) {
    const topics = TOPICS[cat]!;
    const target = targets.categories[cat]!;
    const def = DEFAULTS[cat]!;
    const parsed: Parsed[] = [];
    for (const lv of DIFFICULTIES as Level[]) {
      const list = topics[lv] ?? [];
      if (list.length !== target.by_difficulty[lv]) errors.push(`${cat} ${lv}: 題材 ${list.length} 件 ≠ 目標 ${target.by_difficulty[lv]} 件`);
      list.forEach((line, i) => parsed.push(parseLine(line, lv, (i + 0.5) / list.length)));
    }
    const prefix = idPrefix(cat);
    const pinnedNums = new Set<number>();
    for (const p of parsed) {
      if (!p.pinned) continue;
      if (!p.pinned.startsWith(`${prefix}-`)) errors.push(`${p.pinned} は ${cat} の接頭辞ではない`);
      const n = Number(p.pinned.split("-")[1]);
      if (pinnedNums.has(n)) errors.push(`${p.pinned} が二重にピン留めされている`);
      pinnedNums.add(n);
      usedPinned.add(p.pinned);
    }
    // 難易度リスト内の相対位置で交互に並べる（同順位は難易度順）→ 空き番号を小さい順に割り当て
    const free = parsed.filter((p) => !p.pinned).sort((a, b) => a.order - b.order || a.level.localeCompare(b.level));
    const freeNums: number[] = [];
    for (let n = 1; freeNums.length < free.length; n++) if (!pinnedNums.has(n)) freeNums.push(n);
    free.forEach((p, i) => (p.pinned = `${prefix}-${String(freeNums[i]).padStart(4, "0")}`));

    for (const p of parsed) {
      const id = p.pinned!;
      const r = real.get(id);
      const style = (p.style ?? def.style) as SeedT["company_style"];
      let seed: SeedT = {
        id,
        category: cat,
        difficulty: p.level,
        time_limit: (p.time ?? def.time[p.level]) as SeedT["time_limit"],
        title: p.title,
        one_line: p.one_line,
        nfr: p.nfr,
        languages_planned: p.langs ?? def.langs,
        company_style: style,
        status: "seed",
      };
      if (r) {
        if (r.meta.category !== cat) errors.push(`${id}: 実物のカテゴリ ${r.meta.category} ≠ ${cat}`);
        if (r.meta.difficulty !== p.level) errors.push(`${id}: 実物の難易度 ${r.meta.difficulty} ≠ 種表の枠 ${p.level}（どちらかを直す）`);
        const realStyle = r.meta.tags.company_style.find((s): s is SeedT["company_style"] => s === "pixiv" || s === "m3" || s === "generic");
        seed = {
          ...seed,
          title: r.meta.title,
          time_limit: r.meta.time_limit,
          languages_planned: [...r.meta.languages],
          company_style: realStyle ?? style,
          nfr: r.meta.tags.nfr.length ? [...r.meta.tags.nfr] : seed.nfr,
          status: r.meta.tier === "core" ? "core" : "generated",
        };
      }
      seeds.push(Seed.parse(seed));
    }
  }
  for (const id of real.keys()) if (!usedPinned.has(id)) errors.push(`${id} は problems/ に実在するが種表でピン留めされていない（TOPICS に "@${id} ..." を足す）`);
  const titles = new Map<string, string>();
  for (const s of seeds) {
    const prev = titles.get(s.title);
    if (prev) errors.push(`タイトル重複: ${prev} と ${s.id}「${s.title}」`);
    titles.set(s.title, s.id);
  }
  if (seeds.length !== targets.total) errors.push(`合計 ${seeds.length} 件 ≠ ${targets.total}`);
  if (errors.length) {
    console.error(errors.join("\n"));
    process.exit(1);
  }
  seeds.sort((a, b) => CATEGORIES.indexOf(a.category) - CATEGORIES.indexOf(b.category) || a.id.localeCompare(b.id));
  const out = path.join(catalogDir(root), "seeds.json");
  await fs.writeFile(out, JSON.stringify(seeds, null, 1) + "\n", "utf8");
  const st = { seed: 0, core: 0, generated: 0 };
  for (const s of seeds) st[s.status]++;
  console.log(`${out} に ${seeds.length} 件を書きました（seed ${st.seed} / core ${st.core} / generated ${st.generated}）`);
}

main().catch((e) => {
  console.error(e instanceof Error ? e.stack ?? e.message : String(e));
  process.exit(1);
});
